def L(who, text, on='down', sfx='', vis=''): S.append(('L', who, text, dict(on=on, sfx=sfx, vis=vis)))
def snd(beats, sfx, vis=''): S.append(('S', '', sfx, dict(beats=beats, vis=vis)))
def rest(beats): S.append(('R', '', '', dict(beats=beats)))

