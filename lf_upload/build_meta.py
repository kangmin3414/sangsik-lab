for k, fn in SRC.items():
    t = open(fn).read()
    sec = dict(re.findall(r'\[([^\]]+)\]\n(.*?)(?=\n\[[^\]]+\]\n|\Z)', t, re.S))
    title = sec['제목 · 확정 (궁금증형)'].strip().split('\n')[0]
    desc = sec['설명란'].strip()
    desc = re.sub(r'(📌 타임스탬프\n)(?:\d\d:\d\d .*\n)+', lambda m: m.group(1) + CH[k] + '\n', desc)
    tags = [x.strip() for x in sec['태그'].replace('\n', ',').split(',') if x.strip()]
    # chapter sanity: ascending, >=10 s apart
    ts = [int(l[:2]) * 60 + int(l[3:5]) for l in CH[k].split('\n')]
    assert ts[0] == 0 and all(b - a >= 10 for a, b in zip(ts, ts[1:])), (k, ts)
    out[k] = {'title': title, 'desc': desc, 'tags': tags}
